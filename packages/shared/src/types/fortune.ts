/** Hexagram mapping school — all locally reproducible. */
export type HexagramSchool = 'daymaster' | 'meihua' | 'liuyao'

export const HEXAGRAM_SCHOOLS: HexagramSchool[] = ['daymaster', 'meihua', 'liuyao']

export interface FortuneAiProviderConfig {
  id: string
  name: string
  baseUrl: string
  apiFormat: 'openai' | 'anthropic'
  models: AiModelConfig[]
  apiKey: string
  /**
   * Media protocol profile for image/video/music.
   * `auto` suggests from Base URL; user may override in Settings.
   */
  mediaProfile?: MediaProfileId
  /** Optional dedicated models (fall back to chat model / adapter default). */
  imageModel?: string
  videoModel?: string
  musicModel?: string
}

export interface FortuneSettings {
  /** Recommended default: daymaster (日主 + 当日干支映射). */
  hexagramSchool: HexagramSchool
  /** Optional AI copy polish; default off. */
  aiPolish: boolean
  /** OpenAI-compatible base URL, e.g. https://api.openai.com/v1 */
  aiBaseUrl: string
  /** Provider display name. */
  aiProviderName: string
  /** API protocol format. */
  aiApiFormat: 'openai' | 'anthropic'
  /** Available model ids for quick selection. */
  aiModels: string[]
  /** OpenAI-compatible model id. */
  aiModel: string
  /** API key for online AI analysis. */
  aiApiKey: string
  /** Multi-provider configurations. */
  aiProviders: FortuneAiProviderConfig[]
  /** Active provider id in aiProviders. */
  aiActiveProviderId: string
}

