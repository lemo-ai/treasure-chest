export type FortuneInputMode = 'birthDate' | 'bazi'

export interface BirthProfile {
  id: string
  name: string
  inputMode: FortuneInputMode
  /** YYYY-MM-DD when inputMode is birthDate */
  birthDate?: string
  birthCalendar?: BirthCalendar
  hourBranch?: BirthHourBranch
  /** Four pillars when inputMode is bazi, e.g. 甲子 */
  yearPillar?: string
  monthPillar?: string
  dayPillar?: string
  hourPillar?: string
  updatedAt: string
}

export interface BaZiSnapshot {
  year: string
  month: string
  day: string
  hour: string | null
  dayMaster: string
  hourKnown: boolean
  animal: string
  yinYang: 'yang' | 'yin'
  element: string
}

export type FortuneLevel = 'excellent' | 'good' | 'fair' | 'caution'

export type HexagramTendency = 'favorable' | 'neutral' | 'caution'

export interface HexagramInfo {
  id: number
  name: string
  nameFull: string
  nameEn: string
  tendency: HexagramTendency
}

export type FortuneAspectKey = 'career' | 'wealth' | 'relationship' | 'health' | 'mood'

export interface FortuneAspect {
  score: number
  level: FortuneLevel
  blurb: string
}

export interface DailyFortune {
  date: string
  profileId: string
  bazi: BaZiSnapshot
  hexagram: HexagramInfo & {
    summary: string
    advice: string
  }
  overall: {
    score: number
    level: FortuneLevel
    blurb: string
  }
  aspects: Record<FortuneAspectKey, FortuneAspect>
  lucky: {
    colors: string[]
    directions: string[]
    numbers: number[]
  }
  disclaimer: string
  /**
   * Optional “AI analysis”/copy supplement.
   * It can be generated by local fallback logic or an online AI provider.
   */
  aiAnalysis?: string
  source: {
    engine: string
    aiPolished: boolean
  }
}

export interface FortuneAiRequest {
  fortune: DailyFortune
  locale: string
}

export interface FortuneAiResponse {
  ok: boolean
  text?: string
  error?: string
}

export interface FortuneAiConnectionTestInput {
  provider: FortuneAiProviderConfig
  model: string
}

export interface FortuneAiConnectionTestResponse {
  ok: boolean
  message: string
}
